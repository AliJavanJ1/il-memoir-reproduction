"""LaTeX tables of the report, written from the values recomputed by verify_results.py.

Every number in these tables comes from the saved run files (runs/jobs/*); nothing is typed by
hand.  Called by verify_results.py; writes report/generated/tab_*.tex.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

GOAL = {"goal_5_1": "(5,1)", "goal_5_5": "(5,5)", "goal_1_5": "(1,5)"}
GOALS = ["goal_5_1", "goal_5_5", "goal_1_5"]
LAYOUT = {"open": "open", "four_rooms": "four rooms"}
LAB = {"f-PG[js]": r"\fPG{} (JS)", "f-PG[kl_dq]": r"\fPG{} ($\KL(d\Vert q)$)", "f-PG[kl_qd]": r"\fPG{} ($\KL(q\Vert d)$)",
       "DM_FB": r"\DMFB", "ER_FB": r"\ERFB", "DM_FB/no_orth": r"\DMFB, no orth.", "ER_FB/no_orth": r"\ERFB, no orth.",
       "expert": "expert"}
CORE_METHODS = ["f-PG[js]", "DM_FB", "ER_FB"]


def f(x, d=3):
    if x is None:
        return "--"
    if abs(x) < 0.5 * 10 ** (-d) and x != 0:
        return f"{x:.{d}f}"
    return f"{x:.{d}f}"


def ms(rec, m, d=3):
    if m not in rec:
        return "--"
    mu, sd = rec[m]["mean"], rec[m]["sd"]
    return f"${f(mu, d)}\\pm{f(sd, d)}$"


def kfmt(x):
    if x is None:
        return "--"
    return f"{x / 1000:g}k" if x >= 1000 else str(int(x))


def span(lo, hi, d):
    """'lo--hi' at d decimals, or a single value when both ends print identically."""
    a, b = f"{lo:.{d}f}", f"{hi:.{d}f}"
    return a if a == b else f"{a}--{b}"


def write(path: Path, text: str) -> str:
    path.write_text(text, encoding="utf-8")
    return path.name


def header(comment: str) -> str:
    return ("% GENERATED by report/verify/make_tables.py from the saved run files (runs/jobs/*).\n"
            f"% {comment}\n% Do not edit by hand: rerun  python3 report/verify/verify_results.py\n")


def write_all(out: Path, N, summary, conv, costs, fbdiag, rows, final, manifests, jobs):
    out.mkdir(parents=True, exist_ok=True)
    written = []

    # ------------------------------------------------------------------ finite results
    lines = [header("Finite mazes, core suite: final held-out metrics, mean +/- sample SD over seeds 0, 1, 2."),
             r"\begin{tabular}{@{}llrcccc@{}}", r"\toprule",
             r"layout, goal & method & $V^\star_H$ & JS (nats) & success & gap to $V^\star_H$ & $\JS^{\SA}$ (nats)\\",
             r"\midrule"]
    for lay in ("open", "four_rooms"):
        for g in GOALS:
            vh = N["finite.expert.V_H_star"][f"{lay}/{g}"]
            for k, m in enumerate(CORE_METHODS):
                rec = summary[("core", "finite", lay, g, m)]
                first = f"{LAYOUT[lay]} {GOAL[g]}" if k == 0 else ""
                vcol = f"{vh:.2f}" if k == 0 else ""
                lines.append(f"{first} & {LAB[m]} & {vcol} & {ms(rec, 'js_nats')} & {ms(rec, 'success')} & "
                             f"{ms(rec, 'gap', 2)} & {ms(rec, 'js_sa_nats')}\\\\")
            if not (lay == "four_rooms" and g == GOALS[-1]):
                lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_finite.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ continuous results
    lines = [header("Continuous maze, core suite: final held-out metrics, mean +/- sample SD over seeds 0, 1, 2."),
             r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
             r"goal & method & JS (nats) & success & return & final in goal\\", r"\midrule"]
    for g in GOALS:
        for k, m in enumerate(CORE_METHODS + ["expert"]):
            rec = summary[("core", "continuous", "four_rooms", g, m)]
            first = GOAL[g] if k == 0 else ""
            js = ms(rec, "js_nats", 4) if m == "expert" else ms(rec, "js_nats")
            lines.append(f"{first} & {LAB[m]} & {js} & {ms(rec, 'success')} & {ms(rec, 'return', 2)} & "
                         f"{ms(rec, 'final_in_goal')}\\\\")
        if g != GOALS[-1]:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_continuous.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ operational thresholds
    lines = [header("Operational thresholds JS <= 0.10 nats and success >= 0.80: seeds meeting them at the last "
                    "checkpoint, and the first checkpoint at which each seed met them (seed order 0, 1, 2)."),
             r"\begin{tabular}{@{}lllcl@{}}", r"\toprule",
             r"maze & goal & method & met at last & first reached (seeds 0, 1, 2)\\", r"\midrule"]
    for env, lay in (("finite", "open"), ("finite", "four_rooms"), ("continuous", "four_rooms")):
        for g in GOALS:
            for k, m in enumerate(CORE_METHODS):
                cs = [conv[("core", env, lay, g, m, s)] for s in (0, 1, 2)]
                n_last = sum(1 for c in cs if c["met_last"])
                firsts = ", ".join("--" if c["first"] is None else kfmt(c["first"]) for c in cs)
                unit = "transitions" if m.startswith("f-PG") else "FB updates"
                maze = (f"{env} {LAYOUT[lay]}" if env == "finite" else "continuous") if (g == GOALS[0] and k == 0) else ""
                lines.append(f"{maze} & {GOAL[g] if k == 0 else ''} & {LAB[m]} & {n_last}/3 & {firsts} ({unit})\\\\")
            if not (env == "continuous" and g == GOALS[-1]):
                lines.append(r"\addlinespace" if g != GOALS[-1] else r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_convergence.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ ablations
    lines = [header("Compact ablations, finite four rooms, goal (5,5): final held-out metrics (mean +/- SD, seeds 0-2) "
                    "and first checkpoint meeting the thresholds per seed."),
             r"\begin{tabular}{@{}lccccl@{}}", r"\toprule",
             r"method & JS (nats) & success & gap to $V^\star_H$ & $\JS^{\SA}$ (nats) & first reached (seeds 0, 1, 2)\\",
             r"\midrule"]
    for m in ("f-PG[js]", "f-PG[kl_dq]", "f-PG[kl_qd]", "midrule", "ER_FB", "ER_FB/no_orth", "DM_FB", "DM_FB/no_orth"):
        if m == "midrule":
            lines.append(r"\midrule")
            continue
        rec = summary[("compact_ablations", "finite", "four_rooms", "goal_5_5", m)]
        cs = [conv[("compact_ablations", "finite", "four_rooms", "goal_5_5", m, s)] for s in (0, 1, 2)]
        firsts = ", ".join("--" if c["first"] is None else kfmt(c["first"]) for c in cs)
        unit = "transitions" if m.startswith("f-PG") else "FB updates"
        lines.append(f"{LAB[m]} & {ms(rec, 'js_nats')} & {ms(rec, 'success')} & {ms(rec, 'gap', 2)} & "
                     f"{ms(rec, 'js_sa_nats')} & {firsts} ({unit})\\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_ablation.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ costs
    def cagg(env, lab, field):
        vals = [o[field] for o in costs["core"] if o["env"] == env and o["label"] == lab]
        mu = sum(vals) / len(vals)
        return mu, min(vals), max(vals), len(vals)

    lines = [header("Cost accounting, core suite (CPU, 4 PyTorch threads): mean over the runs of each environment class "
                    "(finite: 18 per method; continuous: 9).  Wall times in seconds: per-task phase timers (result.json), "
                    "FB pretraining including the recorded replay generation.  ER_FB and DM_FB share one evaluation job per "
                    "adaptation: its cost is printed once for the pair."),
             r"\begin{tabular}{@{}llrrrrrr@{}}", r"\toprule",
             r" & & \multicolumn{2}{c}{one task} & \multicolumn{2}{c}{amortized over 3 goals} & \multicolumn{2}{c}{held-out evaluation}\\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(l){7-8}",
             r"maze & method & transitions & wall (s) & transitions & wall (s) & transitions & wall (s)\\", r"\midrule"]
    for env in ("finite", "continuous"):
        for k, m in enumerate(CORE_METHODS):
            one_s = cagg(env, m, "one_steps")[0]
            one_w = cagg(env, m, "one_wall")[0]
            am_s = cagg(env, m, "am_steps")[0]
            am_w = cagg(env, m, "am_wall")[0]
            ev_s = cagg(env, m, "eval_steps")[0]
            ev_w = cagg(env, m, "eval_wall")[0]
            if m == "DM_FB":            # the evaluation job shared with ER_FB (AUDIT.md L1): one joint cell for both rows
                if (cagg(env, "ER_FB", "eval_steps")[0], round(cagg(env, "ER_FB", "eval_wall")[0], 9)) != (ev_s, round(ev_w, 9)):
                    raise ValueError(f"{env}: ER_FB and DM_FB evaluation costs differ; they should come from one shared job")
                ev = f"\\multirow{{2}}{{*}}{{{ev_s:,.0f}}} & \\multirow{{2}}{{*}}{{{ev_w:.2f}}}"
            elif m == "ER_FB":
                ev = " & "
            else:
                ev = f"{ev_s:,.0f} & {ev_w:.2f}"
            lines.append(f"{env if k == 0 else ''} & {LAB[m]} & {one_s:,.0f} & {one_w:.2f} & {am_s:,.0f} & {am_w:.2f} & "
                         f"{ev}\\\\".replace(",", "{,}"))
        if env == "finite":
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_costs.tex", "\n".join(lines) + "\n"))

    # cost components (phase breakdown)
    def comp(env, key):
        v = N[f"cost.{env}.{key}"]
        return v[0], v[1]
    lines = [header("Cost components per phase (core suite): per-task phase timers (result.json); mean and sample SD over "
                    "runs, and for FB pretraining over the distinct models (6 finite, 3 continuous), each counted once."),
             r"\begin{tabular}{@{}lrr@{}}", r"\toprule", r"phase & finite & continuous\\", r"\midrule"]
    rows_c = [
        ("expert demonstrations (transitions, every method)", "400", "400"),
        ("FB task-blind replay (transitions, once per layout and seed)",
         f"{N['cost.finite.fb_steps'][0]:,}", f"{N['cost.continuous.fb_steps'][0]:,}"),
        ("FB replay resets", f"{N['cost.finite.fb_resets'][0]:,}", f"{N['cost.continuous.fb_resets'][0]:,}"),
        ("FB updates (batch 128 + target batch 128)", f"{N['cost.finite.fb_updates'][0]:,}", f"{N['cost.continuous.fb_updates'][0]:,}"),
        ("FB pretraining wall time per model (s)", "$%.1f\\pm%.1f$" % comp("finite", "fb_wall"), "$%.1f\\pm%.1f$" % comp("continuous", "fb_wall")),
        ("\\ERFB{} latent at the final snapshot (s)", "$%.4f$" % comp("finite", "er_adapt_wall")[0], "$%.4f$" % comp("continuous", "er_adapt_wall")[0]),
        ("\\DMFB{} 300 latent steps at the final snapshot (s)", "$%.2f\\pm%.2f$" % comp("finite", "dm_adapt_wall"), "$%.2f\\pm%.2f$" % comp("continuous", "dm_adapt_wall")),
        ("new transitions during latent adaptation", "0", "0"),
        ("\\fPG{} learner transitions per task", f"{int(N['cost.finite.f-PG[js].one_steps'][0]):,}",
         f"{int(N['cost.continuous.f-PG[js].one_steps'][0]):,}"),
        ("\\fPG{} policy updates per task", f"{N['cost.finite.fpg_updates'][0]}", f"{N['cost.continuous.fpg_updates'][0]}"),
        ("\\fPG{} wall time per task (s)", "$%.2f\\pm%.2f$" % comp("finite", "f-PG[js].one_wall"), "$%.1f\\pm%.1f$" % comp("continuous", "f-PG[js].one_wall")),
    ]
    for a, b, c in rows_c:
        lines.append(f"{a} & {b} & {c}\\\\".replace(",0", "{,}0") if False else f"{a} & {b.replace(',', '{,}')} & {c.replace(',', '{,}')}\\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_cost_components.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ FB diagnostics
    lines = [header("FB diagnostics at the final pretraining snapshot (core and ablation FB models). "
                    "Ranges over the 3 goals that share a model where a quantity depends on the goal."),
             r"\begin{tabular}{@{}llcrrrrrcc@{}}", r"\toprule",
             r"model & seed & $\lambda_{\min}(\hat G_B)$ & $\lambda_{\max}$ & $\lVert\hat G_B-I\rVert_F$ & "
             r"$\overline{F^\top\!\!\int\! B\,d\hat\nu}$ & $\lVert z_{ER}\rVert$ & entropy (nats) & sup TV error & max $|Q-F^\top z_r|$\\",
             r"\midrule"]
    groups = defaultdict(list)
    for s in ("core", "compact_ablations"):
        for d in fbdiag[s]:
            groups[(d["env"], d["layout"], d["variant"], d["seed"])].append(d)
    order = [("finite", "open", "base"), ("finite", "four_rooms", "base"), ("finite", "four_rooms", "no_orth"),
             ("continuous", "four_rooms", "base")]
    for env, lay, var in order:
        for seed in (0, 1, 2):
            ds = groups[(env, lay, var, seed)]
            seen = set()
            ds = [d for d in ds if not (d["adapt_job"] in seen or seen.add(d["adapt_job"]))]
            d0 = ds[0]
            name = {("finite", "open", "base"): "finite open", ("finite", "four_rooms", "base"): "finite four rooms",
                    ("finite", "four_rooms", "no_orth"): "four rooms, no orth.",
                    ("continuous", "four_rooms", "base"): "continuous"}[(env, lay, var)] if seed == 0 else ""
            ern = [d["er_norm"] for d in ds]
            ent = [d["er_ent"] for d in ds] + [d["dm_ent"] for d in ds]
            if env == "finite":
                tv = [d["er_tv"] for d in ds] + [d["dm_tv"] for d in ds]
                q = [d["er_q"] for d in ds] + [d["dm_q"] for d in ds]
                tvs = span(min(tv), max(tv), 1)
                qs = span(min(q), max(q), 1)
            else:
                tvs = qs = "n/a"
            lmin = f"{d0['lmin']:.3f}" if d0["lmin"] >= 1e-3 else f"${d0['lmin']*1e5:.1f}\\times10^{{-5}}$"
            lines.append(f"{name} & {seed} & {lmin} & {d0['lmax']:.2f} & {d0['dev']:.2f} & {d0['FmeanB']:.2f} & "
                         f"{span(min(ern), max(ern), 2)} & {span(min(ent), max(ent), 2)} & {tvs} & {qs}\\\\")
        if (env, lay, var) != order[-1]:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_fbdiag.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ per-seed table (appendix)
    lines = [header("Every completed run: final held-out JS and success per seed (core and compact ablations)."),
             r"\begin{longtable}{@{}lllccccccl@{}}",
             r"\caption{Every final run: held-out divergence (nats) and success at the last checkpoint for each seed, "
             r"and the seeds that meet the operational thresholds there (JS $\le0.10$ and success $\ge0.80$). "
             r"Finite values are exact; continuous values are Monte Carlo estimates (500 rollouts).}\label{tab:seeds}\\",
             r"\toprule",
             r"maze & goal & method & JS s0 & JS s1 & JS s2 & succ.\ s0 & succ.\ s1 & succ.\ s2 & met\\", r"\midrule\endfirsthead",
             r"\toprule",
             r"maze & goal & method & JS s0 & JS s1 & JS s2 & succ.\ s0 & succ.\ s1 & succ.\ s2 & met\\", r"\midrule\endhead",
             r"\bottomrule\endfoot"]
    for suite, env, lay, gl, methods in (("core", "finite", "open", GOALS, CORE_METHODS),
                                         ("core", "finite", "four_rooms", GOALS, CORE_METHODS),
                                         ("core", "continuous", "four_rooms", GOALS, CORE_METHODS + ["expert"]),
                                         ("compact_ablations", "finite", "four_rooms", ["goal_5_5"],
                                          ["f-PG[kl_dq]", "f-PG[kl_qd]", "ER_FB/no_orth", "DM_FB/no_orth"])):
        for g in gl:
            for k, m in enumerate(methods):
                rec = summary[(suite, env, lay, g, m)]
                js = [rec["js_nats"]["values"][s] for s in (0, 1, 2)]
                su = [rec["success"]["values"][s] for s in (0, 1, 2)]
                maze = (("finite " + LAYOUT[lay]) if env == "finite" else "continuous") if k == 0 else ""
                if suite == "compact_ablations" and k == 0:
                    maze = "ablation, four rooms"
                d = 4 if m == "expert" else 3
                met = [str(sd) for sd, (a, b) in enumerate(zip(js, su)) if a <= 0.10 and b >= 0.80]
                mets = ("s" + ", s".join(met)) if met else "none"
                lines.append(f"{maze} & {GOAL[g] if k == 0 else ''} & {LAB[m]} & " + " & ".join(f(x, d) for x in js)
                             + " & " + " & ".join(f(x) for x in su) + f" & {mets}\\\\")
            lines.append(r"\addlinespace")
    lines[-1] = lines[-1]
    lines += [r"\end{longtable}"]
    written.append(write(out / "tab_seeds.tex", "\n".join(lines) + "\n"))

    # ------------------------------------------------------------------ pilot (tuning scope)
    pman = json.loads((Path(out).parents[1] / "runs" / "suites" / "pilot" / "manifest.json").read_text())
    pil = {}
    root = Path(out).parents[1] / "runs" / "jobs"
    for j in pman["jobs"]:
        if j["type"] != "eval":
            continue
        tgt = next(x for x in pman["jobs"] if x["job_id"] == j["identity"]["target"])
        evs = [json.loads(l) for l in (root / j["job_id"] / "outputs" / "evaluations.jsonl").read_text().splitlines() if l.strip()]
        if tgt["type"] == "fpg":
            last = max(evs, key=lambda r: r["coords"]["iteration"])
            key = ("fpg", j["labels"]["env"], tgt["identity"]["fpg"]["lr"], tgt["identity"]["fpg"]["density"])
            pil[key] = last["metrics"]
        else:
            fbj = next(x for x in pman["jobs"] if x["job_id"] == tgt["identity"]["fb_job"])
            tau = fbj["identity"]["fb"]["tau"]
            er = [r for r in evs if r["method"] == "er" and r["coords"]["final_fb_snapshot"]][0]
            dm = [r for r in evs if r["method"] == "dm" and r["coords"]["final_fb_snapshot"] and r["coords"]["final_dm_step"]][0]
            pil[("er", j["labels"]["env"], tau)] = er["metrics"]
            pil[("dm", j["labels"]["env"], tau)] = dm["metrics"]
    lines = [header("Learning pilot (seed 999, four rooms, goal (5,5)): held-out metrics at the last checkpoint. "
                    "Used only to freeze settings; not a result."),
             r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
             r"setting & value & \multicolumn{2}{c}{finite: JS / success} & \multicolumn{2}{c}{continuous: JS / success}\\",
             r"\midrule"]
    for lf, lc in ((0.03, 0.0003), (0.1, 0.001), (0.3, 0.003)):
        a = pil[("fpg", "finite", lf, "kde")]
        b = pil[("fpg", "continuous", lc, "kde")]
        frozen = r" (frozen)" if lf == 0.3 else ""
        lines.append(f"\\fPG{{}} learning rate & {lf:g} / {lc:g}{frozen} & {a['js_nats']:.3f} & {a['success']:.3f} & "
                     f"{b['js_nats']:.3f} & {b['success']:.3f}\\\\")
    h = pil[("fpg", "continuous", 0.001, "histogram")]
    lines.append(f"\\fPG{{}} histogram signal & lr 0.001 & -- & -- & {h['js_nats']:.3f} & {h['success']:.3f}\\\\")
    lines.append(r"\midrule")
    for tau in (0.1, 0.3, 1.0):
        for meth, nm in (("er", r"\ERFB"), ("dm", r"\DMFB")):
            a = pil[(meth, "finite", tau)]
            b = pil[(meth, "continuous", tau)]
            frozen = r" (frozen)" if tau == 1.0 else ""
            lines.append(f"{nm}, $\\tau$ & {tau:g}{frozen} & {a['js_nats']:.3f} & {a['success']:.3f} & "
                         f"{b['js_nats']:.3f} & {b['success']:.3f}\\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    written.append(write(out / "tab_pilot.tex", "\n".join(lines) + "\n"))
    return written
